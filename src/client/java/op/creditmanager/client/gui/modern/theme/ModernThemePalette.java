package op.creditmanager.client.gui.modern.theme;

public final class ModernThemePalette {
    public final int overlay;
    public final int panel;
    public final int panelAlt;
    public final int card;
    public final int cardHover;
    public final int border;
    public final int text;
    public final int muted;
    public final int primary;
    public final int accent;
    public final int success;
    public final int danger;
    public final int warning;
    public final int buttonPrimary;
    public final int buttonDanger;
    public final int buttonNeutral;
    public final int buttonGold;
    public final int navActive;
    public final int navHover;
    public final int selection;
    public final int shadow;

    public ModernThemePalette(int overlay, int panel, int panelAlt, int card, int cardHover, int border,
                              int text, int muted, int primary, int accent, int success, int danger, int warning,
                              int buttonPrimary, int buttonDanger, int buttonNeutral, int buttonGold,
                              int navActive, int navHover, int selection, int shadow) {
        this.overlay = overlay;
        this.panel = panel;
        this.panelAlt = panelAlt;
        this.card = card;
        this.cardHover = cardHover;
        this.border = border;
        this.text = text;
        this.muted = muted;
        this.primary = primary;
        this.accent = accent;
        this.success = success;
        this.danger = danger;
        this.warning = warning;
        this.buttonPrimary = buttonPrimary;
        this.buttonDanger = buttonDanger;
        this.buttonNeutral = buttonNeutral;
        this.buttonGold = buttonGold;
        this.navActive = navActive;
        this.navHover = navHover;
        this.selection = selection;
        this.shadow = shadow;
    }
}
